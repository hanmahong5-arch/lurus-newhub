	deploymentsRoute.POST("/", middleware.RootAuth(), handler.CreateDeployment)
	deploymentsRoute.GET("/:id", handler.GetDeployment)
	deploymentsRoute.GET("/:id/logs", handler.GetDeploymentLogs)
